create or replace function private.validate_product_publication()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.is_active then
    if nullif(btrim(new.name), '') is null
      or nullif(btrim(new.slug), '') is null
      or nullif(btrim(new.sku), '') is null then
      raise exception 'Active products require name, slug and SKU.'
        using errcode = '23514';
    end if;

    if not exists (
      select 1
      from public.product_images pi
      join public.media_assets ma on ma.id = pi.media_id
      where pi.product_id = new.id
        and pi.is_primary
        and ma.status = 'active'
        and ma.archived_at is null
    ) then
      raise exception 'Active products require one active primary image.'
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

create trigger validate_product_publication
before insert or update of is_active, name, slug, sku, archived_at
on public.products
for each row execute function private.validate_product_publication();

create or replace function private.validate_affected_product_image()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  affected_product_id bigint;
  affected_product_ids bigint[];
begin
  if tg_op = 'INSERT' then
    affected_product_ids := array[new.product_id];
  elsif tg_op = 'DELETE' then
    affected_product_ids := array[old.product_id];
  else
    affected_product_ids := array[old.product_id, new.product_id];
  end if;

  for affected_product_id in
    select distinct product_id
    from unnest(affected_product_ids) as affected(product_id)
    where product_id is not null
  loop
    if exists (
      select 1
      from public.products p
      where p.id = affected_product_id
        and p.is_active
    ) and not exists (
      select 1
      from public.product_images pi
      join public.media_assets ma on ma.id = pi.media_id
      where pi.product_id = affected_product_id
        and pi.is_primary
        and ma.status = 'active'
        and ma.archived_at is null
    ) then
      raise exception 'An active product must retain one active primary image.'
        using errcode = '23514';
    end if;
  end loop;

  return coalesce(new, old);
end;
$$;

create constraint trigger validate_affected_product_image
after insert or update or delete on public.product_images
deferrable initially deferred
for each row execute function private.validate_affected_product_image();

create or replace function private.prevent_archiving_published_primary_media()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if (new.status = 'archived' or new.archived_at is not null)
    and exists (
      select 1
      from public.product_images pi
      join public.products p on p.id = pi.product_id
      where pi.media_id = new.id
        and pi.is_primary
        and p.is_active
        and p.archived_at is null
    ) then
    raise exception 'Primary media for an active product cannot be archived.'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger prevent_archiving_published_primary_media
before update of status, archived_at on public.media_assets
for each row execute function private.prevent_archiving_published_primary_media();

