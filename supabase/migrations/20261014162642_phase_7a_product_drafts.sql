create table public.product_drafts (
  id bigint generated by default as identity primary key,
  product_id bigint not null unique references public.products(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_by uuid not null default auth.uid() references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index product_drafts_updated_at_idx
  on public.product_drafts (updated_at desc);

create index product_drafts_created_by_idx
  on public.product_drafts (created_by);

create trigger set_product_drafts_updated_at
before update on public.product_drafts
for each row execute function private.set_updated_at();

alter table public.product_drafts enable row level security;

revoke all on public.product_drafts from public, anon, authenticated;
revoke all on sequence public.product_drafts_id_seq from public, anon, authenticated;
grant select, insert, update, delete on public.product_drafts to authenticated;
grant usage, select on sequence public.product_drafts_id_seq to authenticated;

create policy product_drafts_select_admin
on public.product_drafts
for select
to authenticated
using ((select private.is_admin()));

create policy product_drafts_insert_admin
on public.product_drafts
for insert
to authenticated
with check ((select private.is_admin()) and created_by = (select auth.uid()));

create policy product_drafts_update_admin
on public.product_drafts
for update
to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()) and created_by = (select auth.uid()));

create policy product_drafts_delete_admin
on public.product_drafts
for delete
to authenticated
using ((select private.is_admin()));

create or replace function public.save_product_draft(
  p_product_id bigint,
  p_payload jsonb
)
returns table (draft_id bigint, product_id bigint)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_product_id bigint := p_product_id;
begin
  if jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Product draft payload must be an object.' using errcode = '22023';
  end if;

  if v_product_id is null then
    insert into public.products (
      category_id,
      slug,
      sku,
      name,
      short_description,
      description,
      price,
      is_price_visible,
      is_quote_only,
      min_quantity,
      quantity_step,
      is_featured,
      is_active,
      sort_order,
      seo_title,
      seo_description
    ) values (
      nullif(p_payload ->> 'category_id', '')::bigint,
      nullif(btrim(p_payload ->> 'slug'), ''),
      nullif(btrim(p_payload ->> 'sku'), ''),
      nullif(btrim(p_payload ->> 'name'), ''),
      nullif(btrim(p_payload ->> 'short_description'), ''),
      nullif(btrim(p_payload ->> 'description'), ''),
      nullif(p_payload ->> 'price', '')::numeric,
      coalesce((p_payload ->> 'is_price_visible')::boolean, true),
      coalesce((p_payload ->> 'is_quote_only')::boolean, false),
      greatest(coalesce((p_payload ->> 'min_quantity')::integer, 1), 1),
      greatest(coalesce((p_payload ->> 'quantity_step')::integer, 1), 1),
      coalesce((p_payload ->> 'is_featured')::boolean, false),
      false,
      coalesce((p_payload ->> 'sort_order')::integer, 0),
      nullif(btrim(p_payload ->> 'seo_title'), ''),
      nullif(btrim(p_payload ->> 'seo_description'), '')
    )
    returning id into v_product_id;
  elsif not exists (select 1 from public.products where id = v_product_id) then
    raise exception 'Product not found.' using errcode = 'P0002';
  end if;

  insert into public.product_drafts (product_id, payload, created_by)
  values (v_product_id, p_payload, (select auth.uid()))
  on conflict on constraint product_drafts_product_id_key do update
    set payload = excluded.payload,
        created_by = excluded.created_by
  returning public.product_drafts.id, public.product_drafts.product_id
  into draft_id, product_id;

  return next;
end;
$$;

create or replace function public.publish_product_draft(p_draft_id bigint)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_draft public.product_drafts%rowtype;
  v_product_id bigint;
  v_payload jsonb;
begin
  select * into v_draft
  from public.product_drafts
  where id = p_draft_id
  for update;

  if not found then
    raise exception 'Product draft not found.' using errcode = 'P0002';
  end if;

  v_product_id := v_draft.product_id;
  v_payload := v_draft.payload;

  if nullif(btrim(v_payload ->> 'name'), '') is null
    or nullif(btrim(v_payload ->> 'slug'), '') is null
    or nullif(btrim(v_payload ->> 'sku'), '') is null
    or nullif(v_payload ->> 'category_id', '') is null then
    raise exception 'Published products require name, slug, SKU and category.' using errcode = '23514';
  end if;

  if jsonb_typeof(coalesce(v_payload -> 'images', '[]'::jsonb)) <> 'array'
    or jsonb_array_length(coalesce(v_payload -> 'images', '[]'::jsonb)) = 0 then
    raise exception 'Published products require a primary image.' using errcode = '23514';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(v_payload -> 'images') image
    where nullif(image ->> 'media_id', '') is null
       or nullif(btrim(image ->> 'alt_text'), '') is null
  ) then
    raise exception 'Every product image requires an id and alt text.' using errcode = '23514';
  end if;

  update public.products
  set is_active = false
  where id = v_product_id;

  delete from public.product_collections where product_id = v_product_id;
  delete from public.product_images where product_id = v_product_id;

  update public.products
  set category_id = (v_payload ->> 'category_id')::bigint,
      slug = btrim(v_payload ->> 'slug'),
      sku = btrim(v_payload ->> 'sku'),
      name = btrim(v_payload ->> 'name'),
      short_description = nullif(btrim(v_payload ->> 'short_description'), ''),
      description = nullif(btrim(v_payload ->> 'description'), ''),
      price = nullif(v_payload ->> 'price', '')::numeric,
      is_price_visible = coalesce((v_payload ->> 'is_price_visible')::boolean, true),
      is_quote_only = coalesce((v_payload ->> 'is_quote_only')::boolean, false),
      min_quantity = (v_payload ->> 'min_quantity')::integer,
      quantity_step = (v_payload ->> 'quantity_step')::integer,
      is_featured = coalesce((v_payload ->> 'is_featured')::boolean, false),
      sort_order = coalesce((v_payload ->> 'sort_order')::integer, 0),
      seo_title = nullif(btrim(v_payload ->> 'seo_title'), ''),
      seo_description = nullif(btrim(v_payload ->> 'seo_description'), ''),
      archived_at = null
  where id = v_product_id;

  insert into public.product_collections (product_id, collection_id)
  select v_product_id, value::bigint
  from jsonb_array_elements_text(coalesce(v_payload -> 'collection_ids', '[]'::jsonb));

  insert into public.product_images (product_id, media_id, alt_text, sort_order, is_primary)
  select
    v_product_id,
    (image.value ->> 'media_id')::bigint,
    btrim(image.value ->> 'alt_text'),
    image.ordinality::integer - 1,
    image.ordinality = 1
  from jsonb_array_elements(v_payload -> 'images') with ordinality as image(value, ordinality);

  update public.products
  set is_active = true
  where id = v_product_id;

  delete from public.product_drafts where id = p_draft_id;
  return v_product_id;
end;
$$;

revoke all on function public.save_product_draft(bigint, jsonb) from public, anon;
revoke all on function public.publish_product_draft(bigint) from public, anon;
grant execute on function public.save_product_draft(bigint, jsonb) to authenticated;
grant execute on function public.publish_product_draft(bigint) to authenticated;
